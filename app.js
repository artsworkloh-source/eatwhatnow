function mealForTime(date) {
  const minutes = date.getHours() * 60 + date.getMinutes();
  if (minutes >= 5 * 60 && minutes < 10 * 60 + 30) return "breakfast";
  if (minutes >= 10 * 60 + 30 && minutes < 16 * 60) return "lunch";
  return "dinner";
}

function foodOk(food) {
  if (!diet || diet.any) return true;
  if (diet.halal && !food.halal) return false;
  if (diet.veg && !food.veg) return false;
  if (diet.mild && food.spicy) return false;
  return true;
}

// Extra words only narrow the search. They do not mean a shop is certified.
function searchWords(food, extra) {
  const words = [food.mapQuery];
  if (diet && diet.halal) words.push("halal");
  if (diet && diet.veg) words.push("vegetarian");
  if (extra) words.push(extra);
  return words.join(" ");
}

function mapsUrl(food) {
  return "https://www.google.com/maps/search/?api=1&query=" + encodeURIComponent(searchWords(food, "near me"));
}

function openNowUrl(food) {
  return "https://www.google.com/maps/search/?api=1&query=" + encodeURIComponent(searchWords(food, "open now"));
}

