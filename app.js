function pick() {
  if (spinning) return;
  const meal = showMeal();
  const all = FOODS[meal].filter(foodOk);
  if (!all.length) {
    showEmpty();
    return;
  }
  let choices = all.filter((food) => food !== current);
  if (!choices.length) choices = all;
  const chosen = choices[Math.floor(Math.random() * choices.length)];
  const finish = () => {
    current = chosen;
    showFood(chosen);
    playChime();
  };
  if (matchMedia("(prefers-reduced-motion: reduce)").matches || all.length < 2) {
    finish();
    return;
  }
  spinning = true;
  sharePanel.hidden = true;
  pickButton.hidden = true;
  emptyCard.hidden = true;
  dailyCard.hidden = true;
  afterRow.hidden = true;
  mapLink.hidden = true;
  openLink.hidden = true;
  hintEl.hidden = true;
  againButton.hidden = true;
  halalNote.hidden = true;
  descEl.hidden = true;
  card.hidden = false;
  stage.classList.add("top");
  appScreen.classList.add("grow");
  const start = Math.floor(Math.random() * all.length);
  let step = 0;
  const ticks = 9;
  flashFood(all[start]);
  spinTimer = setInterval(() => {
    step++;
    if (step >= ticks) {
      stopSpin();
      finish();
      return;
    }
    flashFood(all[(start + step) % all.length]);
  }, 80);
}

