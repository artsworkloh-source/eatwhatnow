function loadDiet() {
  try {
    const raw = localStorage.getItem(DIET_KEY);
    if (!raw) return null;
    const saved = JSON.parse(raw);
    if (!saved || typeof saved !== "object") return null;
    return { any: !!saved.any, halal: !!saved.halal, veg: !!saved.veg, mild: !!saved.mild };
  } catch (e) {
    return null;
  }
}

