// Linear acceleration above 15, or about 22 with gravity included (a still phone sits near 9.8).
// One shake waits 1.2s before it can draw again.
function hypot(x, y, z) {
  const xx = x || 0;
  const yy = y || 0;
  const zz = z || 0;
  return Math.sqrt(xx * xx + yy * yy + zz * zz);
}
function shakeInfo(e) {
  const a = e.acceleration;
  if (a && (a.x != null || a.y != null || a.z != null)) return { mag: hypot(a.x, a.y, a.z), limit: 15 };
  const g = e.accelerationIncludingGravity;
  if (g && (g.x != null || g.y != null || g.z != null)) return { mag: hypot(g.x, g.y, g.z), limit: 22 };
  return null;
}
function canShakeNow() {
  if (spinning || document.hidden || appScreen.hidden) return false;
  if (!prefScreen.hidden || !voteScreen.hidden || !dailyCard.hidden || !sharePanel.hidden) return false;
  return true;
}
function onMotion(e) {
  const info = shakeInfo(e);
  if (!info || info.mag < info.limit) return;
  const now = Date.now();
  if (now - lastShake < 1200) return;
  if (!canShakeNow()) return;
  lastShake = now;
  countEvent("摇一摇");
  pick();
}
function listenShake() {
  if (shakeListening) return;
  shakeListening = true;
  addEventListener("devicemotion", onMotion);
}
function isHandheld() {
  const ua = navigator.userAgent || "";
  if (/Android|iPhone|iPad|iPod/i.test(ua)) return true;
  return navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1;
}
function setupShake() {
  if (typeof DeviceMotionEvent === "undefined") return;
  const needsAsk = typeof DeviceMotionEvent.requestPermission === "function";
  if (isHandheld() && needsAsk) {
    shakeEnable.hidden = false;
    return;
  }
  if (isHandheld()) shakeHint.hidden = false;
  listenShake();
}

