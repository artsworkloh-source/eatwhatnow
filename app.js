async function cardBlob(food, meal) {
  const key = food.id + "|" + meal + "|" + LANG;
  if (cardCache && cardCache.key === key) return cardCache.blob;
  if (document.fonts && document.fonts.load) {
    try { await document.fonts.load("200px 'Noto Color Emoji'"); } catch (e) {}
    try { await document.fonts.load("72px 'WenQuanYi Micro Hei'"); } catch (e) {}
  }
  const canvas = drawCard(food, meal);
  const blob = await new Promise((resolve) => canvas.toBlob(resolve, "image/png"));
  if (!blob) throw new Error("png");
  cardCache = { key: key, blob: blob };
  return blob;
}
